/**
 * Reads public/Materials/*.html, extracts <title>, merges with _taxonomy.json,
 * writes data/materials.generated.ts for the React app.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const materialsDir = path.join(root, 'public', 'Materials');
const outFile = path.join(root, 'data', 'materials.generated.ts');

function extractTitle(html) {
  const m = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  return m ? m[1].replace(/\s+/g, ' ').trim() : null;
}

function loadTaxonomy() {
  const taxonomyPath = path.join(materialsDir, '_taxonomy.json');
  const base = {
    defaultCategory: 'general',
    categoryOrder: [],
    categories: {
      general: { ru: 'Рабочие материалы', en: 'Working materials' },
    },
    fileCategory: {},
  };
  if (!fs.existsSync(taxonomyPath)) return base;
  try {
    const raw = JSON.parse(fs.readFileSync(taxonomyPath, 'utf8'));
    return {
      ...base,
      ...raw,
      categories: { ...base.categories, ...(raw.categories || {}) },
      fileCategory: { ...base.fileCategory, ...(raw.fileCategory || {}) },
    };
  } catch (e) {
    console.warn('[materials] Invalid _taxonomy.json, using defaults:', e.message);
    return base;
  }
}

function main() {
  if (!fs.existsSync(materialsDir)) {
    console.warn('[materials] Folder missing:', materialsDir, '(writing empty manifest)');
    const empty = `// AUTO-GENERATED — no public/Materials folder found.
export interface MaterialItem {
  filename: string;
  href: string;
  title: string;
  category: string;
}

export interface MaterialCategoryLabels {
  ru: string;
  en: string;
}

/** category id -> localized labels */
export const MATERIAL_CATEGORY_LABELS: Record<string, MaterialCategoryLabels> = {};

export const MATERIAL_CATEGORY_ORDER: readonly string[] = [];

export const MATERIALS_ITEMS: MaterialItem[] = [];
`;
    fs.mkdirSync(path.dirname(outFile), { recursive: true });
    fs.writeFileSync(outFile, empty);
    return;
  }

  const taxonomy = loadTaxonomy();
  const files = fs
    .readdirSync(materialsDir)
    .filter((f) => f.endsWith('.html') && !f.startsWith('_'))
    .sort((a, b) => a.localeCompare(b));

  const items = files.map((filename) => {
    const full = path.join(materialsDir, filename);
    const html = fs.readFileSync(full, 'utf8');
    const title = extractTitle(html) || filename.replace(/\.html$/i, '').replace(/_/g, ' ');
    const category =
      taxonomy.fileCategory[filename] || taxonomy.defaultCategory || 'general';
    const href = `/Materials/${filename}`;
    return { filename, href, title, category };
  });

  const categoryOrder =
    taxonomy.categoryOrder.length > 0
      ? taxonomy.categoryOrder
      : Object.keys(taxonomy.categories);

  const labelsJson = JSON.stringify(taxonomy.categories, null, 2);
  const orderJson = JSON.stringify(categoryOrder);
  const itemsJson = JSON.stringify(items, null, 2);

  const ts = `// AUTO-GENERATED by scripts/generate-materials-manifest.mjs — do not edit manually.

export interface MaterialItem {
  filename: string;
  href: string;
  title: string;
  category: string;
}

export interface MaterialCategoryLabels {
  ru: string;
  en: string;
}

/** category id → localized labels (from _taxonomy.json) */
export const MATERIAL_CATEGORY_LABELS: Record<string, MaterialCategoryLabels> = ${labelsJson};

/** Preferred ordering of category ids for menus and sections */
export const MATERIAL_CATEGORY_ORDER: readonly string[] = ${orderJson};

export const MATERIALS_ITEMS: MaterialItem[] = ${itemsJson};
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, ts);
  console.log(
    `[materials] Wrote ${items.length} item(s) → ${path.relative(root, outFile)}`,
  );
}

main();
